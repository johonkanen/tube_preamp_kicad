#!/usr/bin/env python3
"""Generate lib/part_map.csv: refdes -> PDF page, symbol, value, Proteus device and package.

Data only; the generator is the shared p2k.part_map (spec keys in its docstring). Sources
(STATUS.md "Phase 1 preparation"): refdes from reference/ipc356_pads.json, value from ROOT.DSN in
source/etunen.pdsprj (= the PDF), device / package from the ROOT.LYT layout records, sheet = the PDF
page whose text layer has the refdes (PAGE_OVERRIDES for the ambiguous ones). No off-board parts on
this board: every part drawn in the PDF has IPC pads (the refdes-like PDF words without pads are net
labels EQ1-EQ3, J1-J4, PRE1, PRE2 and value text J112 / "MMK J04 1µ").

The shared reader handles what the board script did by hand before the shared-tool migration
(STATUS.md "Shared-tool migration 2026-11-20"): the one-letter terminals A-D (p2k candidate 2) and
the Latin-1 µ values C4, C14, C30, C28 / C33-C37 (LATIN1; pilot p2k candidate 1).

  tools/make_part_map.py           write lib/part_map.csv
  tools/make_part_map.py --check   fail if lib/part_map.csv is not up to date
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "p2k"))  # proteus2kicad
from p2k import part_map  # noqa: E402

C, CP, R = "C", "C_Polarized", "R"
SPEC = dict(
    PRJ="source/etunen.pdsprj",
    PDF="source/schematic_pdf/etunen.PDF",
    LATIN1=True,
    SYMBOL_BY_DEVICE={
        # film / ceramic capacitors
        "22N XICON": C, "100N XICON": C, "MMK J01": C, "MMK J04 5MM": C, "CERAMIC56P": C,
        "1N ORANGE DROP": C, "2N2 ORANGE DROP": C, "3N3 ORANGE DROP": C, "4N7 ORANGE DROP": C,
        # electrolytics: C2 / C30 have Proteus pins +/-, C28 / C33-C37 pins 1 (-) / 2 (+)
        "HITEMP10U50V": CP, "MINELECT10U50V": CP, "22µF 450V": "C_Polarized_12",
        "MINRES100K": R, "METALFILM1K": R,
        "1N4001": "D",
        "J112": "J112",
        "G5V-2(HI)": "G5V-2",
        "12AX7": "12AX7",
        "TERMINAL": "PIN",
    },
    # Refdes whose PDF text-layer hits are ambiguous (resolved on the page renders):
    PAGE_OVERRIDES={
        "A": 5, "B": 5, "C": 5, "D": 5,  # the terminals (pads on J1-J4); A-D on pages 1/2 are labels of the B+ nets A-D
        "H4": 3, "H5": 3,                # the terminals (page 3, at U3); H4 / H5 on pages 1-3 are also net labels
    },
    FIELDS=["refdes", "sheet", "lib_id", "value", "device", "package", "proteus_refdes", "off_board"],
    COMMENT="Generated by tools/make_part_map.py - do not edit. sheet = Proteus PDF page; value = schematic"
            " value (ROOT.DSN; the µ values and A-D by override); device/package = Proteus layout record;"
            " Q4 value NADA as in the schematic (STATUS.md finding 1)",
)

if __name__ == "__main__":
    sys.exit(part_map.run(SPEC))
